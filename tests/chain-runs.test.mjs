// Uses an isolated, disposable local PostgreSQL cluster. Never connects to Supabase.
// Requires PostgreSQL initdb, pg_ctl and psql on PATH.
import { after, before, beforeEach, test } from "node:test";
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const exec = promisify(execFile);
const admin = "00000000-0000-0000-0000-000000000001";
const member = "00000000-0000-0000-0000-000000000002";
let directory;
let started = false;
let args;
const sql = async (query) => (await exec("psql", [...args, "-c", query])).stdout.trim();
const literal = (value) => `'${value.replaceAll("'", "''")}'`;
const asUser = (query, uid = admin) => `BEGIN; SET LOCAL ROLE authenticated; SET LOCAL request.jwt.claim.sub = '${uid}'; ${query} COMMIT;`;
async function fails(query, code) {
  await assert.rejects(sql(query), (error) => error.stderr.includes(code));
}

before(async () => {
  directory = await mkdtemp(path.join(tmpdir(), "chain-runs-pg-"));
  const data = path.join(directory, "data");
  await exec("initdb", ["-D", data, "-A", "trust", "-U", "postgres", "--no-locale"]);
  await exec("pg_ctl", ["-D", data, "-l", path.join(directory, "server.log"), "-o", `-F -k ${directory} -h '' -p 55438`, "-w", "start"]);
  started = true;
  args = ["-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-v", "VERBOSITY=verbose", "-h", directory, "-p", "55438", "-U", "postgres", "-d", "postgres"];
  await sql(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE SCHEMA auth;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
      $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    CREATE TABLE public.profiles (id uuid PRIMARY KEY, is_superadmin boolean);
    CREATE TABLE public.prompt_chains (id bigint PRIMARY KEY, name text NOT NULL DEFAULT 'Test chain');
    CREATE TABLE public.prompt_chain_steps (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      prompt_chain_id bigint REFERENCES public.prompt_chains(id),
      step_number integer, prompt_text text, created_at timestamptz DEFAULT now()
    );
    ALTER TABLE public.prompt_chain_steps ENABLE ROW LEVEL SECURITY;
    INSERT INTO public.profiles VALUES ('${admin}', true), ('${member}', false);
    INSERT INTO public.prompt_chains VALUES (1), (2);
  `);
  const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  await sql("GRANT USAGE ON SCHEMA auth TO authenticated; GRANT SELECT ON public.profiles TO authenticated");
  await sql(await readFile(path.join(root, "supabase/sql/prompt-chain-runs.sql"), "utf8"));
});

after(async () => {
  if (started) await exec("pg_ctl", ["-D", path.join(directory, "data"), "-m", "immediate", "-w", "stop"]);
  if (directory) await rm(directory, { recursive: true, force: true });
});


beforeEach(async () => {
  await sql(`TRUNCATE public.prompt_chain_runs, public.prompt_chain_steps RESTART IDENTITY;
    INSERT INTO public.prompt_chain_steps (id, prompt_chain_id, step_number, prompt_text) VALUES
      (30, 1, 3, 'Third'), (10, 1, 1, 'First'), (20, 1, 2, 'Second');`);
});
const begin = () => "SELECT public.begin_prompt_chain_run(1, 'Initial input', 'gemini-test')";
const reserve = async () => JSON.parse(await sql(asUser(`${begin()};`)));
const outputs = () => JSON.stringify([10, 20, 30].map((id, index) => ({ step_id: String(id), step_number: index + 1, output: `Output ${index + 1}` })));
const finish = (id, status = "completed", results = outputs(), message = "NULL") =>
  `SELECT public.finish_prompt_chain_run('${id}', '${status}', ${literal(results)}::jsonb, ${message});`;

test("reserves a durable run with ordered prompts and preserves source tables", async () => {
  const run = await reserve();
  assert.equal(run.steps.length, 3);
  assert.equal(run.steps[0].id, "10");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs WHERE status = 'running'"), "1");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_steps"), "3");
});

test("saves final and intermediate outputs and makes repeated completion idempotent", async () => {
  const run = await reserve();
  await sql(asUser(finish(run.id)));
  await sql(asUser(finish(run.id)));
  assert.equal(await sql("SELECT status || ':' || final_output || ':' || jsonb_array_length(step_outputs) FROM public.prompt_chain_runs"), "completed:Output 3:3");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs"), "1");
});

test("rejects partial completion and mismatched outputs without changing the running row", async () => {
  const run = await reserve();
  await fails(asUser(finish(run.id, "completed", "[]")), "22023");
  const wrong = JSON.parse(outputs()); wrong[0].step_id = "999";
  await fails(asUser(finish(run.id, "completed", JSON.stringify(wrong))), "22023");
  assert.equal(await sql("SELECT status || ':' || jsonb_array_length(step_outputs) FROM public.prompt_chain_runs"), "running:0");
  await sql(asUser(finish(run.id, "failed", JSON.stringify(JSON.parse(outputs()).slice(0, 1)), literal("Step 2 failed"))));
  assert.equal(await sql("SELECT status || ':' || error_message || ':' || jsonb_array_length(step_outputs) FROM public.prompt_chain_runs"), "failed:Step 2 failed:1");
});

test("blocks nonadmins, anonymous calls and writes; read policy restricts history", async () => {
  const run = await reserve();
  await fails(asUser(`${begin()};`, member), "42501");
  await fails(`BEGIN; SET LOCAL ROLE anon; ${begin()}; COMMIT;`, "42501");
  await fails(asUser(finish(run.id), member), "42501");
  assert.equal(await sql(asUser("SELECT count(*) FROM public.prompt_chain_runs;", member)), "0");
  assert.equal(await sql(asUser("SELECT count(*) FROM public.prompt_chain_runs;")), "1");
  await fails(asUser("UPDATE public.prompt_chain_runs SET status='failed';"), "42501");
  await fails(asUser("DELETE FROM public.prompt_chain_runs;"), "42501");
});

test("another superadmin cannot finish someone else's run", async () => {
  const run = await reserve();
  await sql(`UPDATE public.profiles SET is_superadmin = true WHERE id = '${member}'`);
  try { await fails(asUser(finish(run.id), member), "PT404"); }
  finally { await sql(`UPDATE public.profiles SET is_superadmin = false WHERE id = '${member}'`); }
});

test("per-user quotas persist across runs and expire abandoned reservations", async () => {
  const stale = await reserve();
  await fails(asUser(`${begin()};`), "PT429");
  await sql("UPDATE public.prompt_chain_runs SET created_at = now() - interval '6 minutes'");
  const second = await reserve();
  assert.equal(await sql(`SELECT status FROM public.prompt_chain_runs WHERE id = '${stale.id}'`), "failed");
  await sql(asUser(finish(second.id)));
  for (let i = 0; i < 3; i++) {
    const run = await reserve(); await sql(asUser(finish(run.id)));
  }
  await fails(asUser(`${begin()};`), "PT429");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs"), "5");
});

test("workspace quota applies across administrators", async () => {
  await sql(`INSERT INTO public.prompt_chain_runs (prompt_chain_id, created_by, chain_name, initial_input, model, status, steps_snapshot, error_message, finished_at)
    SELECT 1, '${member}'::uuid, 'Other chain', 'Input', 'gemini-test', 'failed', '[{"id":"10","step_number":1,"prompt_text":"First"}]'::jsonb, 'Test failure', now() FROM generate_series(1,20)`);
  await fails(asUser(`${begin()};`), "PT429");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs"), "20");
});

test("concurrent reservations admit only one run for the same administrator", async () => {
  const results = await Promise.allSettled([reserve(), reserve()]);
  assert.equal(results.filter((result) => result.status === "fulfilled").length, 1);
  const failure = results.find((result) => result.status === "rejected");
  assert.ok(failure.reason.stderr.includes("PT429"));
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs"), "1");
});

test("input and chain limits reject admission without charging the quota", async () => {
  await fails(asUser("SELECT public.begin_prompt_chain_run(1, repeat('x', 10001), 'gemini-test');"), "22023");
  await fails(asUser("SELECT public.begin_prompt_chain_run(2, 'Input', 'gemini-test');"), "22023");
  await sql("UPDATE public.prompt_chain_steps SET prompt_text = repeat('x', 8001) WHERE id = 20");
  await fails(asUser(`${begin()};`), "22023");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs"), "0");
});

test("deleting a chain retains historical results and quota accounting", async () => {
  const run = await reserve();
  await sql(asUser(finish(run.id)));
  await sql("DELETE FROM public.prompt_chain_steps WHERE prompt_chain_id = 1; DELETE FROM public.prompt_chains WHERE id = 1");
  assert.equal(await sql("SELECT count(*) FROM public.prompt_chain_runs WHERE prompt_chain_id IS NULL AND final_output = 'Output 3'"), "1");
  await sql("INSERT INTO public.prompt_chains (id) VALUES (1)");
});
