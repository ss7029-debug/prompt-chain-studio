// Uses an isolated, disposable local PostgreSQL cluster. Never connects to Supabase.
// Requires PostgreSQL initdb, pg_ctl and psql on PATH.
import { after, before, beforeEach, test } from "node:test";
import assert from "node:assert/strict";
import { execFile, spawn } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const exec = promisify(execFile);
const admin = "00000000-0000-0000-0000-000000000001";
const member = "00000000-0000-0000-0000-000000000002";
let directory;
let started = false;
let args;
const sql = async (query) => (await exec("psql", [...args, "-c", query])).stdout.trim();
const snapshot = () => sql(`SELECT coalesce(jsonb_agg(jsonb_build_object('id', id::text, 'step_number', step_number, 'prompt_text', prompt_text) ORDER BY step_number NULLS LAST, id), '[]') FROM public.prompt_chain_steps WHERE prompt_chain_id = 1`);
const literal = (value) => `'${value.replaceAll("'", "''")}'`;
const call = (operation, expected, id = "NULL", prompt = "NULL", chain = 1) =>
  `SELECT public.manage_prompt_chain_steps(${chain}, '${operation}', ${id}, ${prompt}, ${literal(expected)}::jsonb);`;
const asUser = (query, uid = admin) => `BEGIN; SET LOCAL ROLE authenticated; SET LOCAL request.jwt.claim.sub = '${uid}'; ${query} COMMIT;`;
const rows = () => sql("SELECT string_agg(id || ':' || step_number || ':' || prompt_text, ',' ORDER BY step_number, id) FROM public.prompt_chain_steps WHERE prompt_chain_id = 1");
async function fails(query, code) {
  await assert.rejects(sql(query), (error) => error.stderr.includes(code));
}

before(async () => {
  directory = await mkdtemp(path.join(tmpdir(), "chain-steps-pg-"));
  const data = path.join(directory, "data");
  await exec("initdb", ["-D", data, "-A", "trust", "-U", "postgres", "--no-locale"]);
  await exec("pg_ctl", ["-D", data, "-l", path.join(directory, "server.log"), "-o", `-F -k ${directory} -h '' -p 55437`, "-w", "start"]);
  started = true;
  args = ["-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-v", "VERBOSITY=verbose", "-h", directory, "-p", "55437", "-U", "postgres", "-d", "postgres"];
  await sql(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE SCHEMA auth;
    CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
      $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    CREATE TABLE public.profiles (id uuid PRIMARY KEY, is_superadmin boolean);
    CREATE TABLE public.prompt_chains (id bigint PRIMARY KEY);
    CREATE TABLE public.prompt_chain_steps (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      prompt_chain_id bigint REFERENCES public.prompt_chains(id),
      step_number integer, prompt_text text, created_at timestamptz DEFAULT now()
    );
    ALTER TABLE public.prompt_chain_steps ENABLE ROW LEVEL SECURITY;
    INSERT INTO public.profiles VALUES ('${admin}', true), ('${member}', false);
    INSERT INTO public.prompt_chains VALUES (1), (2);
  `);
  const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  await sql(await readFile(path.join(root, "supabase/sql/prompt-chain-steps.sql"), "utf8"));
});

after(async () => {
  if (started) await exec("pg_ctl", ["-D", path.join(directory, "data"), "-m", "immediate", "-w", "stop"]);
  if (directory) await rm(directory, { recursive: true, force: true });
});

beforeEach(async () => {
  await sql(`TRUNCATE public.prompt_chain_steps RESTART IDENTITY;
    INSERT INTO public.prompt_chain_steps (id, prompt_chain_id, step_number, prompt_text) VALUES
      (10, 1, 1, 'First'), (20, 1, 2, 'Second'), (30, 1, 3, 'Third'), (40, 2, 1, 'Other chain');
    SELECT setval(pg_get_serial_sequence('public.prompt_chain_steps', 'id'), 100);`);
});

test("append, edit and delete a middle step with consecutive numbering", async () => {
  await sql(asUser(call("create", await snapshot(), "NULL", literal("Fourth"))));
  assert.equal(await rows(), "10:1:First,20:2:Second,30:3:Third,101:4:Fourth");
  await sql(asUser(call("edit", await snapshot(), "20", literal("Changed"))));
  assert.equal(await rows(), "10:1:First,20:2:Changed,30:3:Third,101:4:Fourth");
  await sql(asUser(call("delete", await snapshot(), "20")));
  assert.equal(await rows(), "10:1:First,30:2:Third,101:3:Fourth");
});

test("move down and up preserves IDs and prompt text", async () => {
  await sql(asUser(call("down", await snapshot(), "10")));
  assert.equal(await rows(), "20:1:Second,10:2:First,30:3:Third");
  await sql(asUser(call("up", await snapshot(), "10")));
  assert.equal(await rows(), "10:1:First,20:2:Second,30:3:Third");
});

test("renumbers gaps and duplicate positions deterministically", async () => {
  await sql("UPDATE public.prompt_chain_steps SET step_number = CASE WHEN id = 10 THEN 9 ELSE 4 END WHERE prompt_chain_id = 1");
  await sql(asUser(call("up", await snapshot(), "10")));
  assert.equal(await rows(), "20:1:Second,10:2:First,30:3:Third");
});

test("handles empty chains and deleting the final step", async () => {
  await sql("DELETE FROM public.prompt_chain_steps WHERE prompt_chain_id = 1");
  await sql(asUser(call("create", "[]", "NULL", literal("Only"))));
  assert.equal(await rows(), "101:1:Only");
  await sql(asUser(call("delete", await snapshot(), "101")));
  assert.equal(await snapshot(), "[]");
});

test("stale reorders, edits and creates fail without changing rows", async () => {
  const stale = await snapshot();
  await sql(asUser(call("edit", stale, "20", literal("New text"))));
  const current = await rows();
  for (const [operation, id, prompt] of [["down", "10", "NULL"], ["edit", "20", literal("Old text")], ["create", "NULL", literal("New step")]]) {
    await fails(asUser(call(operation, stale, id, prompt)), "PT409");
    assert.equal(await rows(), current);
  }
});

test("rejects missing or foreign steps, invalid prompts, and boundary moves", async () => {
  const state = await snapshot();
  for (const id of ["999", "40"]) await fails(asUser(call("delete", state, id)), "PT404");
  await fails(asUser(call("up", state, "10")), "22023");
  await fails(asUser(call("down", state, "30")), "22023");
  await fails(asUser(call("create", state, "NULL", literal(" \t\n"))), "22023");
  await fails(asUser(call("create", state, "NULL", "repeat('x', 50001)")), "22023");
  await fails(asUser(call("create", state, "NULL", literal("text"), 999)), "PT404");
  assert.equal(await rows(), "10:1:First,20:2:Second,30:3:Third");
  assert.equal(await sql("SELECT prompt_text FROM public.prompt_chain_steps WHERE id=40"), "Other chain");
});

test("blocks anonymous, non-admin and missing-user calls with no direct table grants", async () => {
  const request = call("delete", await snapshot(), "10");
  await fails(asUser(request, member), "42501");
  await fails(`BEGIN; SET LOCAL ROLE authenticated; ${request} COMMIT;`, "42501");
  await fails(`BEGIN; SET LOCAL ROLE anon; ${request} COMMIT;`, "42501");
  assert.equal(await sql("SELECT has_function_privilege('anon', 'public.manage_prompt_chain_steps(bigint,text,bigint,text,jsonb)', 'EXECUTE')"), "f");
  assert.equal(await rows(), "10:1:First,20:2:Second,30:3:Third");
});

test("an error after deletion rolls back both deletion and numbering", async () => {
  // Test-only constraint forces a failure during renumbering after the DELETE.
  await sql("ALTER TABLE public.prompt_chain_steps ADD CONSTRAINT test_failure CHECK (id <> 30 OR step_number <> 2)");
  try {
    await fails(asUser(call("delete", await snapshot(), "20")), "23514");
    assert.equal(await rows(), "10:1:First,20:2:Second,30:3:Third");
  } finally {
    await sql("ALTER TABLE public.prompt_chain_steps DROP CONSTRAINT test_failure");
  }
});

test("concurrent moves serialize and reject the stale second mutation", async () => {
  const state = await snapshot();
  // First transaction performs a move and holds its parent lock until signaled.
  const first = spawn("psql", args, { stdio: ["pipe", "pipe", "pipe"] });
  let errors = "";
  first.stderr.on("data", (chunk) => { errors += chunk; });
  const done = new Promise((resolve) => first.on("close", resolve));
  const locked = new Promise((resolve) => first.stdout.on("data", (chunk) => {
    if (chunk.toString().includes("LOCKED")) resolve();
  }));
  first.stdin.write(`BEGIN; SET LOCAL ROLE authenticated; SET LOCAL request.jwt.claim.sub = '${admin}'; ${call("down", state, "10")} SELECT 'LOCKED';\n`);
  await locked;
  const second = sql(asUser(call("up", state, "30")));
  // Release only once the second transaction is actually waiting on a lock.
  try {
    let waiting = false;
    for (let attempt = 0; attempt < 100; attempt++) {
      waiting = await sql("SELECT EXISTS (SELECT 1 FROM pg_stat_activity WHERE wait_event_type = 'Lock' AND query LIKE '%manage_prompt_chain_steps%')") === "t";
      if (waiting) break;
    }
    assert.ok(waiting, "second mutation should wait on the first transaction");
  } finally {
    first.stdin.end("COMMIT;\n");
  }
  assert.equal(await done, 0, errors);
  await assert.rejects(second, (error) => error.stderr.includes("PT409"));
  assert.equal(await rows(), "20:1:Second,10:2:First,30:3:Third");
});
